const fs = require('node:fs/promises');
const path = require('node:path');
const { withAppBuildGradle, withDangerousMod, withSettingsGradle } = require('expo/config-plugins');

// Keep the checked-in native project portable. Regeneration owns these changes.
module.exports = function withAndroidStudio(config) {
  config = withSettingsGradle(config, config => {
    config.modResults.contents = config.modResults.contents.replace(/[\t ]+$/gm, '');
    return config;
  });
  // AGP's Prefab parser rejects the JNA native-access warning emitted by JDK 24+.
  // Daemon criteria let Studio/CLI share Java 17 without a machine-specific path.
  config = withDangerousMod(config, ['android', async config => {
    const platforms = { 'WINDOWS.X86_64': 'windows/x64', 'LINUX.X86_64': 'linux/x64',
      'LINUX.AARCH64': 'linux/aarch64', 'MAC_OS.X86_64': 'mac/x64', 'MAC_OS.AARCH64': 'mac/aarch64' };
    const criteria = '# Generated by plugins/withAndroidStudio.js\n# AGP Prefab requires a JVM without the JDK 24+ JNA stderr warning.\n' +
      Object.entries(platforms).map(([platform, binary]) =>
        `toolchainUrl.${platform}=https\\://api.adoptium.net/v3/binary/latest/17/ga/${binary}/jdk/hotspot/normal/eclipse\n`).join('') +
      'toolchainVersion=17\n';
    await fs.writeFile(path.join(config.modRequest.platformProjectRoot, 'gradle/gradle-daemon-jvm.properties'), criteria);
    return config;
  }]);
  return withAppBuildGradle(config, config => {
    if (config.modResults.language !== 'groovy') throw new Error('Jom! expects the Expo Groovy Android template.');
    let contents = config.modResults.contents;
    contents = contents.replace(
      /    signingConfigs \{\r?\n        debug \{[\s\S]*?\r?\n        \}\r?\n    \}\r?\n/,
      '    // Debug uses the Android Gradle plugin\'s locally generated debug key.\n',
    );
    contents = contents.replace(
      /(        release \{[\s\S]*?)            signingConfig signingConfigs\.debug\r?\n/,
      '$1',
    );
    const marker = '// Jom! optional native map key; never store a key in native sources.';
    if (!contents.includes(marker)) {
      contents = contents.replace('    defaultConfig {', `    defaultConfig {
        ${marker}
        manifestPlaceholders["GOOGLE_MAPS_ANDROID_API_KEY"] = providers.gradleProperty("GOOGLE_MAPS_ANDROID_API_KEY")
            .orElse(providers.environmentVariable("GOOGLE_MAPS_ANDROID_API_KEY")).getOrElse("")`);
    }
    const stagingMarker = '// Jom! shorter CMake paths allow generated code to build on Windows.';
    if (!contents.includes(stagingMarker)) {
      contents = contents.replace('android {', `android {
    ${stagingMarker}
    externalNativeBuild {
        cmake {
            buildStagingDirectory rootProject.file("../../../.local/cxx/app")
        }
    }
`);
    }
    if (contents.includes("storeFile file('debug.keystore')")) throw new Error('Jom! debug signing customization did not match the Expo template.');
    config.modResults.contents = contents;
    return config;
  });
};
